DO $$
DECLARE t text; p record;
BEGIN
  -- on repart de zéro sur ces tables (anciennes policies historiques incluses)
  FOREACH t IN ARRAY ARRAY['artisans','calls','appointments','devis','relances'] LOOP
    FOR p IN SELECT policyname FROM pg_policies WHERE schemaname = 'public' AND tablename = t LOOP
      EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', p.policyname, t);
    END LOOP;
  END LOOP;
END $$;

-- artisans : la ligne de l'artisan = son id d'auth
CREATE POLICY artisans_select_own ON public.artisans FOR SELECT TO authenticated USING (id = auth.uid());
CREATE POLICY artisans_insert_own ON public.artisans FOR INSERT TO authenticated WITH CHECK (id = auth.uid());
CREATE POLICY artisans_update_own ON public.artisans FOR UPDATE TO authenticated USING (id = auth.uid()) WITH CHECK (id = auth.uid());
-- pas de DELETE côté client (suppression de compte = via le support / service_role)

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['calls','appointments','devis','relances'] LOOP
    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING (artisan_id = auth.uid())', t || '_select_own', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR INSERT TO authenticated WITH CHECK (artisan_id = auth.uid())', t || '_insert_own', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated USING (artisan_id = auth.uid()) WITH CHECK (artisan_id = auth.uid())', t || '_update_own', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR DELETE TO authenticated USING (artisan_id = auth.uid())', t || '_delete_own', t);
  END LOOP;
END $$;

