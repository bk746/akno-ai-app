-- colonnes sensibles d'artisans : non modifiables par le client lui-même
-- (un REVOKE par colonne n'a pas d'effet quand l'UPDATE de table est accordé : on passe par un trigger)
CREATE OR REPLACE FUNCTION public.artisans_protect_columns()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF coalesce(auth.role(), '') = 'authenticated' THEN
    NEW.id := OLD.id;
    NEW.lead_key := OLD.lead_key;
    NEW.created_at := OLD.created_at;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS artisans_protect_columns ON public.artisans;
CREATE TRIGGER artisans_protect_columns BEFORE UPDATE ON public.artisans
  FOR EACH ROW EXECUTE FUNCTION public.artisans_protect_columns();

