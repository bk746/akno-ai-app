-- 6. Numérotation sans doublon (devis et factures) : compteur verrouillé par artisan
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.artisan_counters (
  artisan_id uuid NOT NULL REFERENCES public.artisans(id) ON DELETE CASCADE,
  kind text NOT NULL,
  year int NOT NULL DEFAULT 0,
  value int NOT NULL DEFAULT 0,
  PRIMARY KEY (artisan_id, kind, year)
);
ALTER TABLE public.artisan_counters ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.artisan_counters FROM anon, authenticated;

-- next_numero('devis') -> '9088' (sans doublon, même si deux devis partent en même temps)
CREATE OR REPLACE FUNCTION public.next_numero(p_kind text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE uid uuid := auth.uid(); v int; start_v int;
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'not authenticated'; END IF;
  -- Les numéros de FACTURE ne passent pas ici : ils sont attribués à l'émission par emettre_facture()
  -- (sinon un appel isolé créerait un trou dans la numérotation légale).
  IF p_kind = 'devis' THEN
    SELECT coalesce(max(regexp_replace(numero, '\D', '', 'g')::bigint), 9087)::int INTO start_v FROM devis
      WHERE artisan_id = uid AND numero ~ '^\D*\d{1,9}\D*$';
    INSERT INTO artisan_counters (artisan_id, kind, year, value) VALUES (uid, 'devis', 0, start_v) ON CONFLICT DO NOTHING;
    UPDATE artisan_counters SET value = greatest(value, start_v) + 1 WHERE artisan_id = uid AND kind = 'devis' AND year = 0 RETURNING value INTO v;
    RETURN v::text;
  END IF;
  RAISE EXCEPTION 'unknown kind %', p_kind;
END $$;
REVOKE ALL ON FUNCTION public.next_numero(text) FROM public, anon;
GRANT EXECUTE ON FUNCTION public.next_numero(text) TO authenticated;

